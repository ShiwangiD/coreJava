// Assignment Operator := Used to assign values to variables.


public class AssignOp {
    public static void main(String[] args){
        int a = 20; // assign
        a += 4;
        int b =5, c=6, d=7;
        b -= 5;
        c *=6;
        d/=5;

        System.out.println("5 add and assign a :"+a);
        System.out.println("5 sub and assign b :"+b);
        System.out.println("5 mult and assign c:"+c);
        System.out.println("5 div and assign d :"+d);


    }
    
}
/*
 1 . =  : assign
 2 . += : add and assign
 3.  -= : sub and assign
 4.  *= : mult and assign
 5.  /= : div and assign

*/
