//Unary Operator := Used with a single operand.
// Type :- 1. increment.
//         2. decrement.


public class UnaryOp {
    public static void main(String[] arg){
        int x = 5;
        int y = 6;
        System.out.println("post increment :"+(x++));
        System.out.println("pre Decrement :"+(--y));
    }
    
}
