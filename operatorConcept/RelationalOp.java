// Relational Operator := Used to compare two values. Result is always true or false.

public class RelationalOp {
    public static void main(String[] args){

        int a =30, b= 40;
    
      System.out.println(a > b);  // ====> false
      System.out.println(a < b);  // =====>true
      System.out.println(a == b); // =====>false
      System.out.println(a >= b); // =====>false
      System.out.println(a <= b); // =====>true
      System.out.println(a != b); // =====> true

    }
    
}


/*
 1. == :--> equal to
 2. != :--> not equal to
 3. >  :--> grater than
 4. <  :--> less than
 5. >= :--> grater or equal
 6. <= :--> less  or equal

*/
