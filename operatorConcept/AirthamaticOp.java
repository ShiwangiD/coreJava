//Airthmatic Operator := Used for mathematical calculations.
public class AirthamaticOp {
    public static void main(String[] args){

        int a = 10, b = 8;

        System.out.println(a + b); 
        System.out.println(a - b); 
        System.out.println(a * b); 
        System.out.println(a / b); 
        System.out.println(a % b);

    }
    
}
/*
 1.+ ===> addition.
 2.- ===> subtraction.
 3.* ===> multification.
 4. / ===> division.
 5. % ===> modulus(remider).
*/
