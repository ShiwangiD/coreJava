// Literals := Literal is a fixed value written directly in the code.(constant value can not change during program execution)

public class Literal {
    public static void main(String[] args){

        int a = 10; // literal ----> 10
        System.out.println("Here literal is :"+a);
        float f = 1.1f;
        System.out.println("Floating point literal :"+f);
        char c = 'a';
        System.out.println("character literal :"+c);
        String s = "hello";
        System.out.println("String literal :"+s);
        boolean b = true;
        System.out.println("boolean literal :"+b);
        String s1= null;
        System.out.println("Null literal :"+s1);


    }
    
}

/*
Types :==>
    1. Integer literals:= 
         Whole numbers without decimal points.
    2. Floating-point literals :=
         Numbers with decimal points.
    3. Character literals :=
          single characters enclosed in single quotes.
    4.  String literals :=   
          Sequence of characters enclosed in double quotes.
    5. Boolean literals :=
          Only two values: true or false.
    6. Null literal :=
          Represents no object reference.                      

*/
